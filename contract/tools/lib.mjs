// contract/tools/lib.mjs — 契约加载与四端渲染。gen.mjs 与 check.mjs 共用。
import { readFileSync, existsSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createHash } from 'node:crypto'

export const DATA_FILES = ['transfer-state.json', 'locales.json', 'strings.json', 'tokens.json', 'capabilities.json', 'products.json']
export const HEADER = 'GENERATED by contract/tools/gen.mjs from contract/*.json — 不要手改，改 contract/ 再跑 gen'

export function sha256(text) {
  return createHash('sha256').update(text).digest('hex')
}

function readJson(root, name) {
  return JSON.parse(readFileSync(join(root, 'contract', name), 'utf8'))
}

/**
 * 读取 contract/locales.json 与 contract/strings/<locale>.json，组装成完整的多语言词典。
 * Phase B 多代理并行翻译时各自只写 contract/strings/<locale>.json，互不冲突。
 */
export function loadSource(root) {
  const localesPath = join(root, 'contract', 'locales.json')
  const locales = existsSync(localesPath) ? readJson(root, 'locales.json') : []
  const stringsDir = join(root, 'contract', 'strings')
  const localeFiles = {}
  if (existsSync(stringsDir)) {
    const knownOrder = locales.map((l) => l.code)
    const diskCodes = readdirSync(stringsDir)
      .filter((f) => f.endsWith('.json'))
      .map((f) => f.slice(0, -5))
    const orderedCodes = [
      ...knownOrder.filter((c) => diskCodes.includes(c)),
      ...diskCodes.filter((c) => !knownOrder.includes(c)).sort(),
    ]
    for (const code of orderedCodes) {
      localeFiles[code] = JSON.parse(readFileSync(join(stringsDir, `${code}.json`), 'utf8'))
    }
  }
  const allKeys = new Set(Object.keys(localeFiles['zh-Hans'] ?? {}))
  for (const dict of Object.values(localeFiles)) {
    for (const k of Object.keys(dict ?? {})) allKeys.add(k)
  }
  const strings = {}
  for (const k of allKeys) {
    strings[k] = {}
    for (const [code, dict] of Object.entries(localeFiles)) {
      if (dict && Object.prototype.hasOwnProperty.call(dict, k)) {
        strings[k][code] = dict[k]
      }
    }
  }
  return { locales, localeFiles, strings }
}

/** 将 contract/strings/*.json 合并写回 contract/strings.json，保持单文件快照同步。 */
export function syncStringsJson(root) {
  const { strings } = loadSource(root)
  if (Object.keys(strings).length > 0) {
    writeFileSync(join(root, 'contract', 'strings.json'), JSON.stringify(strings, null, 2) + '\n')
  }
}

export function loadContract(root) {
  const manifest = readJson(root, 'contract.json')
  const stringsRaw = readFileSync(join(root, 'contract', 'strings.json'), 'utf8')
  const stringsJson = JSON.parse(stringsRaw)
  const source = loadSource(root)
  const stringsJsonUnmodified = manifest.files?.['strings.json'] === sha256(stringsRaw)
  let strings = stringsJson
  if (Object.keys(source.strings).length > 0) {
    if (stringsJsonUnmodified) {
      strings = source.strings
    } else {
      strings = {}
      const keys = new Set([...Object.keys(source.strings), ...Object.keys(stringsJson)])
      for (const k of keys) {
        strings[k] = { ...(source.strings[k] ?? {}), ...(stringsJson[k] ?? {}) }
      }
    }
  }
  return {
    root,
    state: readJson(root, 'transfer-state.json'),
    locales: source.locales,
    localeFiles: source.localeFiles,
    stringsJson,
    strings,
    tokens: readJson(root, 'tokens.json'),
    caps: readJson(root, 'capabilities.json'),
    products: readJson(root, 'products.json'),
    manifest,
  }
}

/** 重新计算 contract.json 应有的内容 */
export function manifestFor(root, version) {
  const files = {}
  for (const f of DATA_FILES) files[f] = sha256(readFileSync(join(root, 'contract', f), 'utf8'))
  return { version, files }
}

const H = (comment) => `${comment} ${HEADER}\n`
const q = (s) => JSON.stringify(s)

function parseColor(v) {
  const m = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(v)
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: +m[4] }
  const hex = v.replace('#', '')
  return { r: parseInt(hex.slice(0, 2), 16), g: parseInt(hex.slice(2, 4), 16), b: parseInt(hex.slice(4, 6), 16), a: 1, hex }
}
const swiftColor = (v) => {
  const c = parseColor(v)
  if (c.hex) return `Color(hex: 0x${c.hex.toUpperCase()})`
  const f = (n) => (n / 255).toFixed(3)
  return `Color(.sRGB, red: ${f(c.r)}, green: ${f(c.g)}, blue: ${f(c.b)}, opacity: ${c.a.toFixed(2)})`
}
const kotlinColor = (v) => {
  const c = parseColor(v)
  const a = Math.round(c.a * 255)
  const hex = [a, c.r, c.g, c.b].map((n) => n.toString(16).padStart(2, '0')).join('').toUpperCase()
  return `0x${hex}L`
}

// ---- wxss ----
function renderWxss(c) {
  const t = c.tokens, n = t.wxssNames, f = t.unit.wxssSpacingFactor
  const lines = [`/* ${HEADER} */`, 'page {']
  for (const grp of ['L', 'D', 'S']) for (const [k, v] of Object.entries(t[grp])) lines.push(`  --${n[grp][k]}: ${v};`)
  for (const [k, v] of Object.entries(t.Sp)) lines.push(`  --${k === 'gutter' ? 'gutter' : k}: ${v * f}rpx;`)
  for (const [k, v] of Object.entries(t.Ty)) lines.push(`  --t-${k}: ${v}${t.unit.typeUnit};`)
  lines.push(`  --font-sans: ${t.font.sans};`, `  --font-mono: ${t.font.mono};`)
  lines.push(`  --d-fast: ${t.motion.fastMs}ms;`, `  --d-base: ${t.motion.baseMs}ms;`, `  --d-slow: ${t.motion.slowMs}ms;`)
  lines.push(`  --e-out: ${t.motion.easeOut};`, `  --e-in: ${t.motion.easeIn};`)
  lines.push(`  --touch-min: ${t.touchMin * f}rpx;`, '}', '')
  const footer = readFileSync(join(c.root, 'contract', 'tools', 'wxss-footer.css'), 'utf8')
  return lines.join('\n') + '\n' + footer
}

